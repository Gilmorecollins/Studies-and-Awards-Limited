// Makes site/js/globe-dots.js: the dots of land on the home page's globe.
//
// Run: node tools/make-globe-dots.mjs
//
// A grid of points spread evenly over the sphere (rows every 1.5 degrees of
// latitude, and along each row about 1.5 degrees of actual distance apart, so
// the dots don't crowd together towards the poles), kept where they fall on
// land. Dots in the six destination countries are gold. The routes run from
// Eldoret to one city in each destination.
//
// The land comes from tools/data/countries-110m.json: Natural Earth's 1:110m
// countries (public domain) in the world-atlas TopoJSON format
// (https://github.com/topojson/world-atlas, ISC licence). Antarctica is left
// out, as on most globes of this kind.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const topo = JSON.parse(readFileSync(join(here, 'data', 'countries-110m.json'), 'utf8'));

const STEP = 1.5; // degrees between rows, and between dots along a row (at the equator)
const SOUTH = -56; // no Antarctica
const NORTH = 82;

// ISO 3166 numeric codes, as in world-atlas
const DESTINATIONS = { '826': 'United Kingdom', '372': 'Ireland', '276': 'Germany', '124': 'Canada', '036': 'Australia', '554': 'New Zealand' };
const ORIGIN = { name: 'Eldoret', lon: 35.27, lat: 0.51 };
const ROUTES = [
  { country: 'United Kingdom', city: 'London', lon: -0.13, lat: 51.51 },
  { country: 'Ireland', city: 'Dublin', lon: -6.26, lat: 53.35 },
  { country: 'Germany', city: 'Berlin', lon: 13.4, lat: 52.52 },
  { country: 'Canada', city: 'Toronto', lon: -79.38, lat: 43.65 },
  { country: 'Australia', city: 'Sydney', lon: 151.21, lat: -33.87 },
  { country: 'New Zealand', city: 'Auckland', lon: 174.76, lat: -36.85 },
];

// ---- TopoJSON: arcs to rings of [lon, lat] ----
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
function ring(indexes) {
  const points = [];
  indexes.forEach((i, n) => {
    const arc = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    points.push(...(n ? arc.slice(1) : arc));
  });
  return points;
}
const countries = topo.objects.countries.geometries.map((g) => {
  const polygons = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
  return { id: g.id, polygons: polygons.map((p) => p.map(ring)) };
});

// even-odd ray casting: inside the outer ring and outside its holes
function inRing(lon, lat, pts) {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i];
    const [xj, yj] = pts[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function countryAt(lon, lat) {
  for (const c of countries) {
    for (const rings of c.polygons) {
      if (inRing(lon, lat, rings[0]) && !rings.slice(1).some((hole) => inRing(lon, lat, hole))) return c.id;
    }
  }
  return null;
}

// ---- the grid ----
const land = [];
const gold = [];
const perDestination = {};
let total = 0;
for (let lat = SOUTH; lat <= NORTH; lat += STEP) {
  const across = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP));
  // each row starts half a step along from the last, so the rows interleave
  const offset = ((lat - SOUTH) / STEP) % 2 ? 0.5 : 0;
  for (let k = 0; k < across; k++) {
    const lon = -180 + ((k + offset) * 360) / across;
    total++;
    const id = countryAt(lon, lat);
    if (!id) continue;
    const pair = [Math.round(lon * 10), Math.round(lat * 10)];
    (DESTINATIONS[id] ? gold : land).push(...pair);
    if (DESTINATIONS[id]) perDestination[DESTINATIONS[id]] = (perDestination[DESTINATIONS[id]] || 0) + 1;
  }
}

const out = `// GENERATED by tools/make-globe-dots.mjs from Natural Earth (public domain)
// via world-atlas. Don't edit by hand: change the tool and run it again.
// The home page globe's dots, as longitude, latitude pairs in tenths of a
// degree: land in grey, the six destination countries in gold. Routes run
// from Eldoret to one city in each destination.
window.GLOBE_DOTS = {
  land: [${land.join(',')}],
  gold: [${gold.join(',')}],
  origin: ${JSON.stringify(ORIGIN)},
  routes: ${JSON.stringify(ROUTES)}
};
`;
writeFileSync(join(here, '..', 'site', 'js', 'globe-dots.js'), out);
console.log(`${land.length / 2} land dots and ${gold.length / 2} gold dots, from ${total} grid points; wrote site/js/globe-dots.js (${Math.round(out.length / 1024)} KB)`);
console.log('gold dots per destination: ' + Object.values(DESTINATIONS).map((n) => `${n} ${perDestination[n] || 0}`).join(', '));
